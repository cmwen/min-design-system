import { writeFileSync } from 'node:fs';

// Static scalable silhouettes; this runs at authoring time, never per frame.
let css = '/* Generated by scripts/generate-waves.mjs. No SVG filters or runtime animation. */\n';
for (let strength = 1; strength <= 12; strength++) {
  const amplitude = strength * 2;
  const inset = amplitude + 1;
  const width = 1000 - inset * 2;
  const height = 600 - inset * 2;
  const parts = [`M${inset} ${inset}`];
  const point = (side, along, offset) => {
    if (side === 0) return [inset + width * along, inset + offset];
    if (side === 1) return [1000 - inset - offset, inset + height * along];
    if (side === 2) return [1000 - inset - width * along, 600 - inset - offset];
    return [inset + offset, 600 - inset - height * along];
  };
  for (let side = 0; side < 4; side++) {
    for (let step = 0; step < 8; step++) {
      const t = step / 8;
      const offset = ((step % 2 ? -1 : 1) * amplitude * 4) / 3;
      const c1 = point(side, t + 1 / 24, offset);
      const c2 = point(side, t + 1 / 12, offset);
      const end = point(side, t + 1 / 8, 0);
      parts.push('C' + [...c1, ...c2, ...end].map((value) => value.toFixed(1)).join(' '));
    }
  }
  const path = parts.join(' ') + 'Z';
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 600" preserveAspectRatio="none"><path fill="white" d="${path}"/></svg>`;
  const selectors = [`[data-ff-wave-strength='${strength}']`];
  // Soft is a whisper; expressive retains the previous soft silhouette.
  if (strength === 1) selectors.push("[data-ff-wave='soft']");
  if (strength === 3) selectors.push("[data-ff-wave='expressive']");
  css += `${selectors.join(',\n')} { --ff-wave-mask: url("data:image/svg+xml,${encodeURIComponent(svg)}"); }\n\n`;
}
writeFileSync('src/waves.css', css);
